/** What a real-but-unsimulated command does, or undefined for an unknown word. */
export const realCommand = (os: OS, name: string): string | undefined => {
  const table = os === 'windows' ? WINDOWS : POSIX;
  const key = os === 'windows' ? name.toLowerCase() : name;
  if (os === 'linux' && (key === 'open' || key === 'pbcopy' || key === 'pbpaste' || key === 'brew')) return undefined;
  if (os === 'mac' && (key === 'xdg-open' || key.startsWith('apt') || key === 'dnf' || key === 'yum' || key === 'pacman' || key === 'snap' || key === 'systemctl' || key === 'free')) return undefined;
  return Object.prototype.hasOwnProperty.call(table, key) ? table[key] : undefined;
};
